import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { tokens } from '../src/tokens.ts';

const kebab = (s: string) => s.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();
const px = (n: number) => `${n}px`;

export function buildCss(): string {
  const lines: string[] = [];
  const add = (name: string, value: string) => lines.push(`  --${name}: ${value};`);

  for (const [k, v] of Object.entries(tokens.color)) add(`color-${kebab(k)}`, v);
  tokens.space.forEach((v, i) => add(`space-${i + 1}`, px(v)));
  for (const [k, v] of Object.entries(tokens.radius)) add(`radius-${kebab(k)}`, px(v));
  for (const [k, v] of Object.entries(tokens.font)) add(`font-${kebab(k)}`, v);
  for (const [k, v] of Object.entries(tokens.size)) add(`size-${kebab(k)}`, px(v));
  add('motion-duration-fast', `${tokens.motion.durationFast}ms`);
  add('motion-duration-base', `${tokens.motion.durationBase}ms`);
  add('motion-easing', tokens.motion.easing);
  for (const [k, v] of Object.entries(tokens.shadow)) add(`shadow-${kebab(k)}`, v);
  add('texture-grain', tokens.texture.grain);

  const body = lines.join('\n');
  return `/* Generated by design/scripts/build-css.ts. Do not edit. */\n:root,\n[data-theme="light"] {\n${body}\n}\n`;
}

/**
 * Writes `content` to `path` unless the file already holds exactly that, so watchers
 * (the web dev server) see no change when the tokens did not change. Returns whether it wrote.
 */
export function writeIfChanged(path: string, content: string): boolean {
  let current: string | undefined;
  try {
    current = readFileSync(path, 'utf8');
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code !== 'ENOENT') throw error;
  }
  if (current === content) return false;
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, content);
  return true;
}

const here = dirname(fileURLToPath(import.meta.url));
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const out = resolve(here, '../dist/tokens.css');
  console.log(writeIfChanged(out, buildCss()) ? `wrote ${out}` : `unchanged ${out}`);
}
