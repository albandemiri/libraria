// Bundles spike/web/entry.js + foliate-js into one inline script and writes
// spike/readerHtml.generated.ts (an HTML string for the WebView).
//   node spike/build-reader-html.mjs   (run from mobile/; esbuild comes from backend/)
import { createRequire } from 'node:module'
import { randomBytes } from 'node:crypto'
import { writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const here = path.dirname(fileURLToPath(import.meta.url))
// esbuild comes from backend/node_modules of this checkout (run `npm ci` in backend/ first).
const require = createRequire(path.join(here, '../../backend/package.json'))
const esbuild = require('esbuild')

const STUBS = /[\\/](pdf|mobi|fb2|comic-book|tts|dict|opds)\.js$|[\\/]vendor[\\/](fflate|pdfjs[\\/].*)\.js$/
const stubPlugin = {
  name: 'stub-unused-formats',
  setup(build) {
    build.onLoad({ filter: STUBS }, () => ({ contents: 'export {}', loader: 'js' }))
  },
}

const result = await esbuild.build({
  entryPoints: [path.join(here, 'web/entry.js')],
  bundle: true,
  format: 'iife',
  target: ['safari16'],
  minify: true,
  write: false,
  legalComments: 'inline',
  plugins: [stubPlugin],
  logLevel: 'warning',
})
const js = result.outputFiles[0].text.replace(/<\/script/gi, '<\\/script')
const nonce = randomBytes(16).toString('base64')

// Top-level policy: only our nonce'd script runs; everything else is local blob:/data:.
const CSP = [
  "default-src 'none'",
  `script-src 'nonce-${nonce}'`,
  "style-src 'unsafe-inline' blob:",
  'img-src blob: data:',
  'font-src blob: data:',
  'media-src blob:',
  'frame-src blob:',
  'connect-src blob: data:',
  "base-uri 'none'",
  "form-action 'none'",
].join('; ')

const html = `<!DOCTYPE html>
<html lang="sq"><head>
<meta charset="utf-8">
<meta http-equiv="Content-Security-Policy" content="${CSP}">
<meta name="viewport" content="width=device-width, initial-scale=1, maximum-scale=1, user-scalable=no, viewport-fit=cover">
<style>html,body{margin:0;height:100%;background:#fff;overflow:hidden}foliate-view{display:block;height:100%;width:100%}</style>
</head><body>
<script nonce="${nonce}">${js}</script>
</body></html>`

writeFileSync(
  path.join(here, 'readerHtml.generated.ts'),
  `// GENERATED by spike/build-reader-html.mjs (foliate-js, MIT). Do not edit.\nexport const READER_HTML = ${JSON.stringify(html)};\n`,
)
console.log(`readerHtml.generated.ts: ${(html.length / 1024).toFixed(0)} KB, script ${(js.length / 1024).toFixed(0)} KB`)
